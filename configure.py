# Helper function for Dolphin libraries
def DolphinLib(lib_name: str, cflags: Any, objects: List[Object]) -> Dict[str, Any]:
    return {
        "lib": lib_name,
        "mw_version": "GC/1.2.5n",
        "cflags": [*cflags, "-DDOLPHIN_SDK"],
        "progress_category": "sdk",
        "src_dir": "libs/dolsdk2004/src",
        "objects": objects,
    }


# Helper function for REL script objects
def Rel(lib_name: str, objects: List[Object]) -> Dict[str, Any]:
    for obj in objects:
        if obj.name not in PCH_EXCLUDE:
            obj.options["extra_cflags"] = [*obj.options["extra_cflags"], "-prefix msl_rel.mch"]
    return {
        "lib": lib_name,
        "src_dir": f"rels/{lib_name}/src",
        "mw_version": "GC/2.6",
        "cflags": [*cflags_rel, f"-i rels/{lib_name}/include"],
        "progress_category": "game",
        "objects": objects,
    }


