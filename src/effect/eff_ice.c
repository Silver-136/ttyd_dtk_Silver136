/** Spawns an ice block at (x, y, z); durations 1..999 count down, other values hold until soft-deleted. Used for the frozen status. */
EffectEntry* effIceEntry(s32 type, s32 duration, f32 x, f32 y, f32 z, f32 scale) {
    EffectEntry* effect;
    EffIceWork* work;

    effect = effEntry();
    effect->type = "Ice";
    effect->count = 1;
    work = __memAlloc(HEAP_EFFECT, sizeof(EffIceWork));
    effect->userdata = work;
    effect->callback = effIceMain;
    effect->flags |= EFFECT_FLAG_SOFT_DELETABLE;
    work->type = type;
    work->position.x = x;
    work->position.y = y;
    work->position.z = z;
    work->scale = scale;
    work->scaleX = 1.0f;
    work->scaleY = 1.0f;
    work->alpha = 1.0f;
    if (duration > 0) {
        work->duration = duration;
    } else {
        work->duration = 1000;
    }
    work->frame = 0;
    work->state = 0;
    work->anim = effMayaAnimAlloc(&ice_effAnimDt);
    effPlayMayaAnim(work->anim);
    return effect;
}

/** Plays the ice block's animation; soft delete starts its final animation phase at frame 90. */
static void effIceMain(EffectEntry* effect) {
    EffIceWork* work = effect->userdata;
    Vec calcPos;
    Vec pos = { 0.0f, 0.0f, 0.0f };
    OSTime now;

    pos.x = work->position.x;
    pos.y = work->position.y;
    pos.z = work->position.z;
    calcPos = pos;

    if (effect->flags & EFFECT_FLAG_SOFT_DELETE) {
        effect->flags &= ~EFFECT_FLAG_SOFT_DELETE;
        work->frame = 90;
        work->state = 1;
        now = gp->inBattle ? gp->renderTime : gp->renderFieldTime;
        work->anim->startTime = OSTicksToMilliseconds(now) - (u64)(1000.0f / gp->framerate) * work->frame;
    }

    switch (work->state) {
        case 0:
            if (work->duration < 1000) {
                work->duration--;
            }
            if (work->duration == 0) {
                work->state = 1;
            }
            if (work->frame < 90) {
                work->frame++;
                effCalcMayaAnim(work->anim);
            }
            break;
        case 1:
            work->frame++;
            effCalcMayaAnim(work->anim);
            break;
        case 2:
            work->frame++;
            if (work->frame % 30 == 0) {
                effKemuTestEntry(1, work->position.x + (f32)(20 - irand((s32)(40.0f * work->scale))),
                                 work->position.y - 30.0f * (1.0f - work->scaleY), work->position.z, 1.0f);
            }
            work->scaleY *= 0.99f;
            work->scaleX *= 1.005f;
            work->alpha *= 0.99f;
            break;
    }

    switch (work->state) {
        case 0:
        case 1:
            if ((f32)work->frame > work->anim->data->endTime) {
                effDeleteMayaAnim(work->anim);
                effDelete(effect);
                return;
            }
            break;
        case 2:
            if (work->frame > 200) {
                effDeleteMayaAnim(work->anim);
                effDelete(effect);
                return;
            }
            break;
    }
    dispEntry(CAMERA_3D, dispCalcZ(&calcPos), DISP_MODE_XLU, effIceDisp, effect);
}

/** Draws the ice block model with its animated joint transforms. */
static void effIceDisp(CameraId cameraId, void* param) {
    EffectEntry* effect = param;
    EffIceWork* work = effect->userdata;
    GXTexObj texObj;
    Mtx trans;
    Mtx rot;
    Mtx mtx;
    Mtx scale;
    Mtx joint;
    s32 i;
    s32 id;

    PSMTXTrans(trans, work->position.x, work->position.y, work->position.z);
    PSMTXRotRad(rot, 'y', 0.017453292f * -camGetPtr(cameraId)->viewYaw);
    PSMTXConcat(trans, rot, mtx);
    PSMTXTrans(trans, 0.0f, -30.0f, 0.0f);
    PSMTXConcat(mtx, trans, mtx);
    PSMTXScale(scale, work->scaleX, work->scaleY, 1.0f);
    PSMTXConcat(mtx, scale, mtx);
    PSMTXTrans(trans, 0.0f, 30.0f, 0.0f);
    PSMTXConcat(mtx, trans, mtx);
    PSMTXScale(scale, 8.0f * work->scale, 8.0f * work->scale, 8.0f * work->scale);
    PSMTXConcat(mtx, scale, mtx);
    GXSetNumChans(1);
    GXSetChanCtrl(GX_COLOR0A0, GX_FALSE, GX_SRC_REG, GX_SRC_REG, GX_LIGHT_NULL, GX_DF_NONE, GX_AF_NONE);
    GXSetNumTexGens(1);
    GXSetTexCoordGen2(GX_TEXCOORD0, GX_TG_MTX2x4, GX_TG_TEX0, GX_IDENTITY, GX_FALSE, GX_PTIDENTITY);
    GXSetNumTevStages(1);
    GXSetTevOrder(GX_TEVSTAGE0, GX_TEXCOORD0, GX_TEXMAP0, GX_COLOR0A0);
    GXSetTevOp(GX_TEVSTAGE0, GX_MODULATE);
    GXSetCurrentMtx(GX_PNMTX0);
    for (i = 1; i < work->anim->data->lists->count; i++) {
        id = 0x20;
        if (i < work->anim->data->lists->count - 1) {
            id = 0x1f;
        }
        effGetTexObj(id, &texObj);
        GXLoadTexObj(&texObj, GX_TEXMAP0);
        if (i < work->anim->data->lists->count - 1) {
            effGetTexObj(0x1f, &texObj);
            GXLoadTexObj(&texObj, GX_TEXMAP0);
            GXSetChanMatColor(GX_COLOR0A0, (GXColor){ 255, 255, 255, (u8)(191.25f * work->alpha) });
        } else {
            effGetTexObj(0x20, &texObj);
            GXLoadTexObj(&texObj, GX_TEXMAP0);
            GXSetChanMatColor(GX_COLOR0A0, (GXColor){ 255, 255, 255, (u8)(127.5f * work->alpha) });
        }
        PSMTXConcat(mtx, work->anim->joints[0].mtx, joint);
        PSMTXConcat(joint, work->anim->joints[i].mtx, joint);
        PSMTXConcat(camGetPtr(cameraId)->view, joint, joint);
        GXLoadPosMtxImm(joint, GX_PNMTX0);
        effDrawMayaPoly(&work->anim->data->lists->polys[i]);
    }
}
