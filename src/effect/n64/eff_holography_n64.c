EffectEntry* effHolographyN64Entry(s32 type, s32 lifetime, f32 x, f32 y, f32 z, f32 scale) {
    EffectEntry* effect;
    EffHolographyN64Work* work;

    effect = effEntry();
    effect->type = "HolographyN64";
    effect->count = 1;
    work = __memAlloc(HEAP_EFFECT, sizeof(EffHolographyN64Work));
    effect->userdata = work;
    effect->callback = effHolographyMain;
    effect->flags |= 2;
    work->type = type;
    work->frame = 0;
    if (lifetime <= 0) {
        work->timer = 1000;
    } else {
        work->timer = lifetime;
    }
    work->alpha = 0;
    work->position.x = x;
    work->position.y = y;
    work->position.z = z;
    work->scale = 0.1f * scale;
    work->r = 70;
    work->g = 180;
    work->b = 120;
    return effect;
}

void effHolographyMain(EffectEntry* effect) {
    EffHolographyN64Work* work = effect->userdata;
    Vec position;
    Vec tmp = {0.0f, 0.0f, 0.0f};
    s32 timer;

    tmp.x = work->position.x;
    tmp.y = work->position.y;
    tmp.z = work->position.z;
    position = tmp;
    if (effect->flags & 4) {
        effect->flags &= ~4;
        work->timer = 16;
    }
    if (work->timer < 1000) {
        work->timer--;
    }
    work->frame++;
    timer = work->timer;
    if (timer < 0) {
        effDelete(effect);
        return;
    }
    if (work->frame < 16) {
        work->alpha = work->frame * 16 + 15;
    } else {
        work->alpha = 255;
    }
    if (timer < 16) {
        work->alpha = timer * 16;
    }
    dispEntry(CAMERA_3D, dispCalcZ(&position), 2, (DispCallback)effHolographyDisp, effect);
}

