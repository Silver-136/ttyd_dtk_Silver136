void* effHolographyN64Entry(s32 type, s32 duration, f32 x, f32 y, f32 z, f32 scale) {
    void* entry = effEntry();
    EffHolographyWork* work;
    s32 flags;
    f32 scaleStep;

    *(char**)((s32)entry + 0x14) = "HolographyN64";
    *(s32*)((s32)entry + 0x8) = 1;
    work = __memAlloc(3, 0x2C);
    *(EffHolographyWork**)((s32)entry + 0xC) = work;
    *(void**)((s32)entry + 0x10) = effHolographyMain;
    flags = *(s32*)entry;
    *(s32*)entry = flags | 2;
    work->type = type;
    work->frame = 0;
    if (duration <= 0) {
        work->timer = 1000;
    } else {
        work->timer = duration;
    }
    scaleStep = float_0p1_804254bc * scale;
    work->alpha = 0;
    work->x = x;
    work->y = y;
    work->z = z;
    work->scaleStep = scaleStep;
    work->colorR = 70;
    work->colorG = 180;
    work->colorB = 120;

    return entry;
}
