void effHolographyMain(void* effEntry) {
    Vec3 dispPos;
    Vec3 pos;
    const Vec3* zero;
    register EffHolographyWork* work;
    s32 flags;
    s32 frame;
    s32 timer;

    work = *(EffHolographyWork**)((s32)effEntry + 0xC);
    zero = &vec3_802fb0f8;
    pos = *zero;
    pos.x = work->x;
    pos.y = work->y;
    pos.z = work->z;
    dispPos = pos;

    flags = *(s32*)effEntry;
    if (flags & 4) {
        *(s32*)effEntry = flags & ~4;
        work->timer = 16;
    }
    if (work->timer < 1000) {
        work->timer--;
    }
    work->frame++;
    timer = work->timer;
    if (timer < 0) {
        effDelete(effEntry);
    } else {
        frame = work->frame;
        if (frame < 16) {
            work->alpha = (frame << 4) + 15;
        } else {
            work->alpha = 0xFF;
        }
        if (timer < 16) {
            work->alpha = timer << 4;
        }
        dispEntry(4, 2, effHolographyDisp, effEntry, dispCalcZ(&dispPos));
    }
}


