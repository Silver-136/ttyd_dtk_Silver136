EffectEntry* effButterflyN64Entry(s32 type, f32 x, f32 y, f32 z) {
    EffectEntry* effect;
    EffButterflyN64Work* work;

    effect = effEntry();
    effect->type = "ButterflyN64";
    effect->count = 1;
    work = __memAlloc(HEAP_EFFECT, sizeof(EffButterflyN64Work));
    effect->userdata = work;
    effect->callback = effButterflyMain;
    effect->flags |= 2;
    work->type = type;
    work->lifetime = 1000;
    work->alpha = 255;
    work->position.x = x;
    work->home.x = x;
    work->position.y = y;
    work->home.y = y;
    work->position.z = z;
    work->home.z = z;
    work->frame = 0;
    work->bobIdx = 0;
    work->timer = 0;
    work->radiusXZ = 50.0f;
    work->radiusY = 30.0f;
    return effect;
}

void effButterflyMain(EffectEntry* effect) {
    EffButterflyN64Work* work = effect->userdata;
    Vec position;
    Vec tmp = {0.0f, 0.0f, 0.0f};
    f32 rad;
    f32 tx, ty, tz;
    f32 dx, dy, dz;
    f32 inv;

    tmp.x = work->position.x;
    tmp.y = work->position.y;
    tmp.z = work->position.z;
    position = tmp;
    if (effect->flags & 4) {
        effect->flags &= ~4;
        work->lifetime = 900;
    }
    if (work->lifetime < 1000) {
        work->lifetime--;
    }
    work->frame++;
    if (work->lifetime < 0) {
        effDelete(effect);
        return;
    }
    if (work->lifetime < 16) {
        work->alpha = work->lifetime * 16;
    }
    work->timer--;
    if (work->timer <= 0) {
        rad = (6.2831855f * (rand() % 360)) / 360.0f;
        tx = work->home.x + work->radiusXZ * (f32)sin(rad);
        ty = work->home.y + (rand() % (s32)work->radiusY);
        tz = work->home.z + work->radiusXZ * (f32)cos(rad);
        work->timer = rand() % 100 + 10;
        dx = tx - work->position.x;
        dy = ty - work->position.y;
        dz = tz - work->position.z;
        if (dx == 0.0f && dy == 0.0f && dz == 0.0f) {
            dx = work->home.x - work->position.x;
            dy = work->home.y - work->position.y;
            dz = work->home.z - work->position.z;
            if (dx == 0.0f && dy == 0.0f && dz == 0.0f) {
                dx = 1.0f;
                dy = 0.0f;
                dz = 0.0f;
            }
        }
        inv = dx * dx + dy * dy + dz * dz;
        if (inv) {
            inv = 1.0f / sqrtf(inv);
        }
        dx *= inv;
        dy *= inv;
        dz *= inv;
        work->velocity.x = dx;
        work->velocity.y = dy;
        work->velocity.z = dz;
        work->rotY = angleABf(0.0f, 0.0f, -work->velocity.x, work->velocity.z);
    }
    work->bobIdx += 3;
    if (work->bobIdx >= 30) {
        work->bobIdx -= 30;
    }
    work->position.x += work->velocity.x;
    work->position.y += work->velocity.y;
    work->position.z += work->velocity.z;
    dispEntry(CAMERA_3D, dispCalcZ(&position), 1, (DispCallback)effButterflyDisp, effect);
}

void effButterflyDisp(CameraId cameraId, EffectEntry* effect) {
    CameraEntry* camera;
    EffButterflyN64Work* work;
    GXTexObj texObj;
    Mtx mtx;
    Mtx scale;
    Mtx rot;
    s32 alpha;
    s32 type;

    camera = camGetPtr(cameraId);
    work = effect->userdata;
    alpha = work->alpha;
    type = work->type;
    PSMTXTrans(mtx, work->position.x, work->position.y + 0.3f * y_data[work->bobIdx], work->position.z);
    PSMTXRotRad(rot, 'y', 0.017453292f * work->rotY);
    PSMTXConcat(mtx, rot, mtx);
    PSMTXScale(scale, 0.02f, 0.02f, 0.02f);
    PSMTXConcat(mtx, scale, mtx);
    PSMTXConcat(camera->view, mtx, mtx);
    GXLoadPosMtxImm(mtx, GX_PNMTX0);
    GXSetCurrentMtx(GX_PNMTX0);
    GXSetTevColor(GX_TEVREG0, (GXColor){alpha, alpha, alpha, 255});
    GXSetNumChans(0);
    GXSetNumTevStages(1);
    GXSetTevOrder(GX_TEVSTAGE0, GX_TEXCOORD0, GX_TEXMAP0, GX_COLOR_NULL);
    GXSetTevColorOp(GX_TEVSTAGE0, GX_TEV_ADD, GX_TB_ZERO, GX_CS_SCALE_1, GX_TRUE, GX_TEVPREV);
    GXSetTevAlphaOp(GX_TEVSTAGE0, GX_TEV_ADD, GX_TB_ZERO, GX_CS_SCALE_1, GX_TRUE, GX_TEVPREV);
    GXSetTevColorIn(GX_TEVSTAGE0, GX_CC_ZERO, GX_CC_C0, GX_CC_TEXC, GX_CC_ZERO);
    GXSetTevAlphaIn(GX_TEVSTAGE0, GX_CA_ZERO, GX_CA_ZERO, GX_CA_ZERO, GX_CA_TEXA);
    GXSetNumTexGens(1);
    GXSetTexCoordGen2(GX_TEXCOORD0, GX_TG_MTX2x4, GX_TG_TEX0, GX_TEXMTX0, GX_FALSE, GX_PTIDENTITY);
    PSMTXScale(scale, 0.03125f, 0.015625f, 0.0f);
    GXLoadTexMtxImm(scale, GX_TEXMTX0, GX_MTX2x4);
    effGetTexObjN64(type + 0x78, &texObj);
    GXLoadTexObj(&texObj, GX_TEXMAP0);
    GXSetCullMode(GX_CULL_NONE);
    effSetVtxDescN64(&but_02_v[work->bobIdx * 6]);
    GXBegin(GX_TRIANGLES, GX_VTXFMT0, 12);
    tri2(0, 1, 2, 0, 0, 2, 3, 0);
    tri2(3, 4, 0, 0, 3, 5, 4, 0);
}
