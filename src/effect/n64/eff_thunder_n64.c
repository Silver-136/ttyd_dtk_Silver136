void effThunderMain(EffectEntry* effect) {
    EffThunderN64Work* work;
    Vec position;
    Vec tmp = {0.0f, 0.0f, 0.0f};
    s32 life;
    s32 frame;
    s32 type;

    work = effect->userdata;

    tmp.x = work->position.x;
    tmp.y = work->position.y;
    tmp.z = work->position.z;
    position = tmp;
    if (effect->flags & EFFECT_FLAG_SOFT_DELETE) {
        effect->flags &= ~EFFECT_FLAG_SOFT_DELETE;
        work->lifetime = 0;
    }
    type = work->type;
    if (work->lifetime < 100) {
        work->lifetime--;
    }
    work->frame++;
    life = work->lifetime;
    if (life < 0) {
        if (work->charge) {
            effDelete(work->charge);
            work->charge = NULL;
        }
        if (work->flare) {
            effDelete(work->flare);
            work->flare = NULL;
        }
        effDelete(effect);
        return;
    }
    frame = work->frame;
    if (work->flare && frame >= 18) {
        effDelete(work->flare);
        work->flare = NULL;
    }
    if (type <= 2 || frame <= 6) {
        work->u0 += work->du0;
        if (work->u0 < 0.0f) {
            work->u0 += 256.0f;
        } else if (work->u0 > 256.0f) {
            work->u0 -= 256.0f;
        }
        if (frame % work->interval0 == 0) {
            work->v0 += work->dv0;
            if (work->v0 < 0.0f) {
                work->v0 += 64.0f;
            } else if (work->v0 > 64.0f) {
                work->v0 -= 64.0f;
            }
        }
        if (frame % work->interval1 == 0) {
            work->u1 += work->du1;
            if (work->u1 < 0.0f) {
                work->u1 += 256.0f;
            } else if (work->u1 > 256.0f) {
                work->u1 -= 256.0f;
            }
        }
        work->v1 += work->dv1;
        if (work->v1 < 0.0f) {
            work->v1 += 64.0f;
        } else if (work->v1 > 64.0f) {
            work->v1 -= 64.0f;
        }
    }
    if (type >= 3) {
        if (frame > 6) {
            work->alpha -= 13;
            if (work->alpha < 0) {
                work->alpha = 0;
            }
        }
    } else if (life < 10) {
        work->alpha -= 25;
        if (work->alpha < 0) {
            work->alpha = 0;
        }
    }

    dispEntry(CAMERA_3D, dispCalcZ(&position), 2, (DispCallback)effThunderDisp, effect);
}

