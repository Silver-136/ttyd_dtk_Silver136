EffectEntry* effShockN64Entry(s32 type, f32 x, f32 y, f32 z, f32 a, f32 b) {
    EffectEntry* effect;
    EffShockN64Work* w;

    effect = effEntry();
    effect->type = "ShockN64";
    effect->count = 1;
    w = __memAlloc(HEAP_EFFECT, sizeof(EffShockN64Work));
    effect->userdata = w;
    effect->callback = effShockMain;
    w->type = type;
    w->age = 0;
    w->life = 30;
    w->c10 = 255;
    w->flashAlpha = 255;
    w->alpha = 255;
    w->position.x = x;
    w->position.y = y;
    w->position.z = z;
    if (type == 2) {
        w->scale = 1.0f;
    } else {
        w->scale = 0.0f;
    }
    w->offset = 0.5f * a;
    w->offset2 = 0.5f * b;
    switch (type) {
    case 0:
    case 1:
    case 3:
        w->col0[0] = 255;
        w->col0[1] = 255;
        w->col0[2] = 0;
        w->col1[0] = 255;
        w->col1[1] = 255;
        w->col1[2] = 255;
        break;
    default:
        w->col0[0] = 70;
        w->col0[1] = 180;
        w->col0[2] = 120;
        w->col1[0] = 255;
        w->col1[1] = 255;
        w->col1[2] = 255;
        break;
    }
    return effect;
}

void effShockMain(EffectEntry* effect) {
    EffShockN64Work* w = effect->userdata;
    Vec position;
    Vec tmp = {0.0f, 0.0f, 0.0f};
    s32 type;
    s32 life;
    s32 age;

    tmp.x = w->position.x;
    tmp.y = w->position.y;
    tmp.z = w->position.z;
    position = tmp;
    type = w->type;
    if (w->life < 100) {
        w->life--;
    }
    w->age++;
    life = w->life;
    if (life < 0) {
        effDelete(effect);
        return;
    }
    age = w->age;
    if (type == 2) {
        if (age <= 20) {
            w->scale *= 1.1f;
        }
    } else {
        w->scale += 0.05f * (8.0f - w->scale);
    }
    w->flashAlpha *= 0.9f;
    if (life < 5) {
        w->alpha *= 0.8f;
    }
    if (age > 6) {
        w->c10 -= 13;
        if (w->c10 < 0) {
            w->c10 = 0;
        }
    }
    dispEntry(CAMERA_3D, dispCalcZ(&position), 2, (DispCallback)effShockDisp, effect);
}

