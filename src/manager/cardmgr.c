s32 cardIsExec(void) {
    void* work = wp;

    if (work == 0) {
        return 0;
    }
    if ((*(volatile u16*)work & 2) != 0) {
        return 1;
    }
    if ((*(volatile u16*)work & 1) != 0) {
        return 1;
    }
    return ((u32)(-*(s32*)((s32)work + 0xEC)) | (u32)*(s32*)((s32)work + 0xEC)) >> 31;
}

